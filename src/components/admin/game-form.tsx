"use client";

import { useRouter } from "next/navigation";
import { useId, useState, useTransition } from "react";
import { useTranslations } from "next-intl";
import { Loader2 } from "lucide-react";
import { createGame, updateGame } from "@/actions/admin/games";
import { uploadViaApi } from "@/lib/upload-client";
import { formatUploadErrorMessage } from "@/lib/upload-errors";
import { Button } from "@/components/ui/button";
import { Input } from "@/components/ui/input";
import { SectionCard } from "@/components/ui/page-header";
import { Textarea } from "@/components/ui/textarea";
import { toast } from "@/hooks/use-toast";
import { STORAGE } from "@/lib/storage";
import { useSlugField } from "@/hooks/use-slug-field";
import { compressImage } from "@/lib/image-compress";
import { SafeImage } from "@/components/ui/safe-image";
import { cn } from "@/lib/utils";

type GameData = {
  id?: string;
  name: string;
  slug: string;
  description?: string | null;
  shortDescription?: string | null;
  seoTitle?: string | null;
  seoDescription?: string | null;
  isFeatured: boolean;
  isActive: boolean;
  sortOrder: number;
  logoUrl?: string | null;
  backgroundUrl?: string | null;
  iconUrl?: string | null;
  bannerUrl?: string | null;
  coverUrl?: string | null;
};

type AssetType = "icon" | "banner" | "cover" | "logo" | "background";

const labelClass = "label-text mb-1.5 block";

export function GameForm({ locale, game }: { locale: string; game?: GameData }) {
  const t = useTranslations("admin.gameEdit");
  const uid = useId();
  const router = useRouter();
  const [pending, startTransition] = useTransition();
  const [name, setName] = useState(game?.name ?? "");
  const { slug, setSlug } = useSlugField(name, game?.slug ?? "");

  async function handleSubmit(e: React.FormEvent<HTMLFormElement>) {
    e.preventDefault();
    const form = new FormData(e.currentTarget);
    const slugValue = slug.trim() || undefined;
    const payload = {
      name: form.get("name") as string,
      slug: slugValue,
      description: (form.get("description") as string) || undefined,
      shortDescription: (form.get("shortDescription") as string) || undefined,
      seoTitle: (form.get("seoTitle") as string) || undefined,
      seoDescription: (form.get("seoDescription") as string) || undefined,
      isFeatured: form.get("isFeatured") === "on",
      isActive: form.get("isActive") === "on",
      sortOrder: Number(form.get("sortOrder") || 0),
    };

    startTransition(async () => {
      const result = game?.id
        ? await updateGame(game.id, payload)
        : await createGame(payload);

      if (result.success) {
        const autoSlug =
          !game?.id &&
          result.data &&
          typeof result.data === "object" &&
          "slugAutoGenerated" in result.data &&
          result.data.slugAutoGenerated;
        toast({
          title: game?.id ? "toast.updated" : "toast.created",
          description: autoSlug ? t("slugGenerated") : undefined,
        });
        router.push(`/${locale}/admin/games`);
        router.refresh();
      } else {
        toast({ title: "toast.error", description: result.error, variant: "destructive" });
      }
    });
  }

  async function uploadAsset(type: AssetType, file: File) {
    if (!game?.id) {
      toast({ title: "toast.saveGameFirst", variant: "destructive" });
      return;
    }
    try {
      const compressed = await compressImage(file, 0.85, type === "icon" ? 512 : 1920).catch(() => file);
      await uploadViaApi({
        file: compressed,
        purpose: "game-asset",
        gameId: game.id,
        assetType: type,
      });
      toast({ title: "toast.uploaded", description: t(`assets.${type}`) });
      router.refresh();
    } catch (err) {
      toast({
        title: "toast.uploadFailed",
        description: formatUploadErrorMessage(err),
        variant: "destructive",
      });
    }
  }

  const assets: { type: AssetType; url: string | null | undefined; preview: string; fit: string; className?: string }[] = game?.id
    ? [
        { type: "logo", url: game.logoUrl, preview: "h-14 w-14", fit: "object-contain p-1" },
        { type: "icon", url: game.iconUrl, preview: "h-14 w-14", fit: "object-cover" },
        { type: "cover", url: game.coverUrl, preview: "h-20 w-14", fit: "object-cover" },
        { type: "banner", url: game.bannerUrl, preview: "h-16 w-full", fit: "object-cover" },
        { type: "background", url: game.backgroundUrl, preview: "h-16 w-full", fit: "object-cover", className: "sm:col-span-2" },
      ]
    : [];

  return (
    <form onSubmit={handleSubmit} className="max-w-2xl space-y-6">
      <SectionCard title={t("generalTitle")}>
        <div className="space-y-4">
          <div>
            <label htmlFor={`${uid}-name`} className={labelClass}>{t("name")}</label>
            <Input id={`${uid}-name`} name="name" value={name} onChange={(e) => setName(e.target.value)} required />
          </div>
          <div>
            <label htmlFor={`${uid}-slug`} className={labelClass}>{t("slug")}</label>
            <Input
              id={`${uid}-slug`}
              name="slug"
              value={slug}
              onChange={(e) => setSlug(e.target.value)}
              placeholder={t("slugPlaceholder")}
              aria-describedby={`${uid}-slug-hint`}
              className="font-mono"
            />
            <p id={`${uid}-slug-hint`} className="meta mt-1">{t("slugHint")}</p>
          </div>
          <div>
            <label htmlFor={`${uid}-short`} className={labelClass}>{t("shortDescription")}</label>
            <Input id={`${uid}-short`} name="shortDescription" defaultValue={game?.shortDescription ?? ""} maxLength={300} placeholder={t("shortDescriptionPlaceholder")} />
          </div>
          <div>
            <label htmlFor={`${uid}-description`} className={labelClass}>{t("description")}</label>
            <Textarea id={`${uid}-description`} name="description" defaultValue={game?.description ?? ""} rows={4} />
          </div>
          <div className="grid gap-4 sm:grid-cols-2">
            <div>
              <label htmlFor={`${uid}-seo-title`} className={labelClass}>{t("seoTitle")}</label>
              <Input id={`${uid}-seo-title`} name="seoTitle" defaultValue={game?.seoTitle ?? ""} />
            </div>
            <div>
              <label htmlFor={`${uid}-order`} className={labelClass}>{t("sortOrder")}</label>
              <Input id={`${uid}-order`} name="sortOrder" type="number" defaultValue={game?.sortOrder ?? 0} className="tabular-nums" />
            </div>
          </div>
          <div>
            <label htmlFor={`${uid}-seo-description`} className={labelClass}>{t("seoDescription")}</label>
            <Textarea id={`${uid}-seo-description`} name="seoDescription" defaultValue={game?.seoDescription ?? ""} rows={2} />
          </div>
          <div className="flex gap-6 text-sm text-ink">
            <label className="flex items-center gap-2">
              <input type="checkbox" name="isFeatured" defaultChecked={game?.isFeatured} className="h-4 w-4 accent-violet" />
              {t("featured")}
            </label>
            <label className="flex items-center gap-2">
              <input type="checkbox" name="isActive" defaultChecked={game?.isActive ?? true} className="h-4 w-4 accent-violet" />
              {t("active")}
            </label>
          </div>
        </div>
      </SectionCard>

      {game?.id && (
        <SectionCard title={t("assetsTitle")} description={t("assetsHint", { cdn: STORAGE.cdn })}>
          <div className="grid gap-4 sm:grid-cols-2 lg:grid-cols-3">
            {assets.map((a) => (
              <div key={a.type} className={a.className}>
                <label htmlFor={`${uid}-asset-${a.type}`} className="label-text block">{t(`assets.${a.type}`)}</label>
                <span className="meta mb-1.5 block">{t(`assetHints.${a.type}`)}</span>
                {a.url && (
                  <div className={cn("relative mb-2 overflow-hidden rounded-md border border-line", a.preview)}>
                    <SafeImage src={a.url} alt="" fill className={a.fit} sizes={a.preview.includes("w-full") ? "200px" : "56px"} />
                  </div>
                )}
                <Input
                  id={`${uid}-asset-${a.type}`}
                  type="file"
                  accept="image/*"
                  onChange={(e) => e.target.files?.[0] && uploadAsset(a.type, e.target.files[0])}
                />
              </div>
            ))}
          </div>
        </SectionCard>
      )}

      <Button type="submit" disabled={pending}>
        {pending && <Loader2 className="h-4 w-4 animate-spin" aria-hidden />}
        {pending ? t("saving") : game?.id ? t("update") : t("create")}
      </Button>
    </form>
  );
}
